const BY_SHOW = new Map<string, Character[]>();
for (const character of CHARACTERS) {
  const list = BY_SHOW.get(character.showId);
  if (list) list.push(character);
  else BY_SHOW.set(character.showId, [character]);
}

const BY_ID = new Map(CHARACTERS.map((character) => [character.id, character]));

/** Characters belonging to one show, in corpus order. */
export function charactersForShow(showId: string): Character[] {
  return BY_SHOW.get(showId) ?? [];
}

export function getCharacter(id: string): Character | undefined {
  return BY_ID.get(id);
}
