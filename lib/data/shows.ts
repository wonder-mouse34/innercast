export const SHOW_BY_ID: Record<string, Show> = Object.fromEntries(
  SHOWS.map((show) => [show.id, show]),
);

export function getShow(id: string | undefined): Show | undefined {
  return id ? SHOW_BY_ID[id] : undefined;
}

/**
 * Neighbours in the library: shows filed under the same situations and themes.
 * Used on the detail screen so a person can step sideways without re-matching.
 */
export function relatedShows(show: Show, limit = 4): Show[] {
  const situations = new Set(show.situations);
  const themes = new Set(show.themes.map((theme) => theme.toLowerCase()));

  return SHOWS.filter((candidate) => candidate.id !== show.id)
    .map((candidate) => {
      const situationOverlap = candidate.situations.filter((id) => situations.has(id)).length;
      const themeOverlap = candidate.themes.filter((theme) =>
        themes.has(theme.toLowerCase()),
      ).length;
      return { candidate, score: situationOverlap * 2 + themeOverlap };
    })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score || a.candidate.title.localeCompare(b.candidate.title))
    .slice(0, limit)
    .map((entry) => entry.candidate);
}

export function commitmentLabel(show: Show): string {
  const totalHours = Math.round((show.episodes * show.runtimeMinutes) / 60);
  const seasonPart = show.seasons === 1 ? '1 season' : `${show.seasons} seasons`;
  return `${seasonPart} · ${show.episodes} eps · ~${show.runtimeMinutes} min · ${totalHours}h total`;
}
