/**
 * `Object.fromEntries` only ever returns `Record<string, Situation>`, so the
 * cast back to `Record<SituationId, Situation>` is unavoidable at the type
 * level. It is safe because `SITUATIONS` is a closed literal array covering
 * every `SituationId` exactly once.
 */
export const SITUATION_BY_ID: Record<SituationId, Situation> = Object.fromEntries(
  SITUATIONS.map((situation) => [situation.id, situation]),
) as Record<SituationId, Situation>;

export function situationLabel(id: SituationId): string {
  return SITUATION_BY_ID[id]?.label ?? id;
}
